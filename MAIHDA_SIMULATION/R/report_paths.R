source('R/project_utils.R')
set_project_root()
report_args <- parse_named_args()
if (length(setdiff(names(report_args), 'run_id'))) stop('Use only --run-id=NAME')
report_id <- arg_value(report_args, 'run_id', 'production500')
if (!grepl('^[A-Za-z0-9_-]+$', report_id)) stop('Invalid run ID')
report_run <- file.path('outputs', '07_event_informed_simulation', report_id)
report_publication <- file.path(report_run, 'publication')
dir.create(file.path(report_publication, 'figures'), recursive=TRUE, showWarnings=FALSE)
dir.create(file.path(report_publication, 'supplementary_tables'), showWarnings=FALSE)
